/** 把檢索到的段落組成「資料區塊」，放進使用者訊息裡交給 Claude（第四章 4.7）。 */
export function buildContextBlock(
  hits: { title: string; text: string }[],
): string {
  if (hits.length === 0) return "<資料>（沒有找到相關資料）</資料>";
  return hits
    .map(
      (h, i) =>
        `<資料 編號="${i + 1}" 來源="${h.title.replace(/"/g, "'")}">\n${h.text}\n</資料>`,
    )
    .join("\n");
}
